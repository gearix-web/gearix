window.updateStatus = async (id, status) => {
  await updateDoc(
    doc(db, "repair_cases", id),

    {
      status: status,

      updatedAt: serverTimestamp(),
    },
  );
};

// ลบเคส

window.deleteCase = async (id) => {
  const result = await Swal.fire({
    title: "ลบเคสนี้?",
    text: "ข้อมูลเคสจะถูกลบออกจากระบบ และไม่สามารถกู้คืนได้",
    icon: "warning",
    showCancelButton: true,
    confirmButtonText: "ลบ",
    cancelButtonText: "ยกเลิก",
  });

  if (!result.isConfirmed) return;

  try {
    await deleteDoc(doc(db, "repair_cases", id));

    Swal.fire({
      icon: "success",
      title: "ลบเคสแล้ว",
      timer: 1000,
      showConfirmButton: false,
    });
  } catch (error) {
    Swal.fire({
      icon: "error",
      title: "เกิดข้อผิดพลาด",
      text: error.message,
    });
  }
};

