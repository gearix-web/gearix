import { auth, db } from "./firebase-config.js";

import {
  onAuthStateChanged,
  signOut,
} from "https://www.gstatic.com/firebasejs/10.13.0/firebase-auth.js";

import {
  collection,
  getDocs,
  addDoc,
  serverTimestamp,
  onSnapshot,
  doc,
  getDoc,
  setDoc,
  updateDoc,
  deleteDoc,
} from "https://www.gstatic.com/firebasejs/10.13.0/firebase-firestore.js";

import { statusMeta } from "./status-map.js";

// true เมื่อ SN ถูกสุ่มให้เองเพราะเครื่องลูกค้าไม่มี SN เดิม (กดปุ่มสุ่ม)
// false ทันทีถ้าแอดมินพิมพ์ SN เอง -> ใช้ตัดสินใจข้อความแจ้งเตือนลูกค้าตอนเปิดเคส
let snAutoGenerated = false;
document.getElementById("sn").addEventListener("input", () => {
  snAutoGenerated = false;
});

// ตรวจสอบ Admin

onAuthStateChanged(auth, (user) => {
  if (!user) {
    location.href = "login.html";

    return;
  }

  loadCustomers();

  loadRepairCases();
});

// โหลดลูกค้า role member

async function loadCustomers() {
  const select = document.getElementById("customerSelect");

  try {
    const snapshot = await getDocs(collection(db, "users"));

    select.innerHTML = `

<option value="">

-- เลือกลูกค้า --

</option>

`;

    snapshot.forEach((item) => {
      const user = item.data();

      if (user.role === "customer") {
        select.innerHTML += `


<option value="${item.id}">

${user.fullname || "-"}

(${user.email || "-"})

</option>


`;
      }
    });

    console.log("โหลดสมาชิกสำเร็จ :", snapshot.size);
  } catch (error) {
    console.error("โหลดลูกค้าไม่ได้", error);
  }
}

// สุ่ม SN ให้เอง ขึ้นต้นด้วย CN- ตามด้วยเลขสุ่มไม่ซ้ำ

document.getElementById("genSnBtn").onclick = async () => {
  const btn = document.getElementById("genSnBtn");

  btn.disabled = true;

  try {
    const snapshot = await getDocs(collection(db, "repair_cases"));

    const existing = new Set(
      snapshot.docs.map((item) => (item.data().sn || "").toUpperCase()),
    );

    let sn;

    do {
      const randomDigits = Math.floor(100000 + Math.random() * 900000);

      sn = `CN-${randomDigits}`;
    } while (existing.has(sn));

    document.getElementById("sn").value = sn;
    snAutoGenerated = true;
  } catch (error) {
    console.error("สุ่ม SN ไม่สำเร็จ", error);

    Swal.fire({
      icon: "error",

      title: "สุ่ม SN ไม่สำเร็จ",

      text: error.message,
    });
  } finally {
    btn.disabled = false;
  }
};

// โหมดลูกค้าในหน้าต่างเปิดเคส: มีบัญชี (account) หรือ ไม่มีบัญชี/วอล์กอิน (guest)
let caseCustomerMode = "guest";
let pendingVisitorRoom = null; // ห้องแชทที่กด "เปิดเคสใหม่ให้ลูกค้ารายนี้" (ถ้ามี) — หลังสร้างเคสจะแปะ caseId กลับ

function setCaseCustomerMode(mode) {
  caseCustomerMode = mode;
  document.querySelectorAll("#caseCustomerMode button").forEach((b) => {
    const on = b.dataset.mode === mode;
    b.classList.toggle("btn-primary", on);
    b.classList.toggle("btn-outline-primary", !on);
  });
  document.getElementById("accountFields").style.display = mode === "account" ? "" : "none";
  document.getElementById("guestFields").style.display = mode === "guest" ? "" : "none";
}

document.querySelectorAll("#caseCustomerMode button").forEach((btn) => {
  btn.addEventListener("click", () => setCaseCustomerMode(btn.dataset.mode));
});

// เรียกจากแชท (admin-chat.js): เตรียมหน้าต่างเปิดเคสให้ลูกค้าที่กำลังคุย
// ลูกค้ามีบัญชี (customerUid) -> เลือกจากรายชื่อบัญชี / วอล์กอิน -> กรอกชื่อ+เบอร์ให้อัตโนมัติ
window.prepareCreateCase = (name, phone, roomId, customerUid) => {
  pendingVisitorRoom = roomId || null;

  const select = document.getElementById("customerSelect");
  const hasOption = customerUid && select.querySelector(`option[value="${customerUid}"]`);

  if (hasOption) {
    setCaseCustomerMode("account");
    select.value = customerUid;
  } else {
    setCaseCustomerMode("guest");
    document.getElementById("guestName").value = name || "";
    document.getElementById("guestPhone").value = phone || "";
  }

  const modal = bootstrap.Modal.getOrCreateInstance(document.getElementById("createRepair"));
  modal.show();
};

// เปิดเคสใหม่ (จ่ายงาน/มอบหมายช่างตัดออก - ช่างจะเป็นคนกดรับงานเองที่หน้าช่าง)
// ลูกค้าไม่มีบัญชีก็เปิดได้ (วอล์กอิน: กรอกชื่อ + เบอร์เอง) เพราะลูกค้าไม่ต้องล็อกอินอีกต่อไป
document.getElementById("createBtn").onclick = async () => {
  try {
    const device = document.getElementById("device").value;
    const sn = document.getElementById("sn").value;
    const detail = document.getElementById("detail").value;

    // --- ลูกค้า: มีบัญชี หรือ วอล์กอิน (ไม่มีบัญชี) ---
    let customerId = null;
    let customerData = null;

    if (caseCustomerMode === "account") {
      customerId = document.getElementById("customerSelect").value;
      if (!customerId) {
        Swal.fire({ icon: "warning", title: "กรุณาเลือกลูกค้า" });
        return;
      }
      const customerSnap = await getDoc(doc(db, "users", customerId));
      if (!customerSnap.exists()) {
        Swal.fire({ icon: "error", title: "ไม่พบข้อมูลลูกค้า" });
        return;
      }
      customerData = customerSnap.data();
      customerData.address = customerData.address || "";
    } else {
      const guestName = document.getElementById("guestName").value.trim();
      const guestPhone = document.getElementById("guestPhone").value.trim();
      if (!guestName) {
        Swal.fire({ icon: "warning", title: "กรุณากรอกชื่อลูกค้า" });
        return;
      }
      customerData = { fullname: guestName, phone: guestPhone };
    }

    if (!device || !detail) {
      Swal.fire({ icon: "warning", title: "กรุณากรอกข้อมูลให้ครบถ้วน" });
      return;
    }

    const caseNo = "RC-" + Date.now();

    // สร้าง Repair Case เป็น pending เสมอ รอช่างมากดรับงานเอง
    const caseRef = await addDoc(
      collection(db, "repair_cases"),
      {
        caseNo: caseNo,
        customerUid: customerId, // null = ลูกค้าไม่มีบัญชี
        customerName: customerData.fullname,
        customerEmail: customerData.email || "",
        customerPhone: customerData.phone || "",
        customerAddress: customerData.address || "",
        sn: sn,
        device: device,
        problem: detail,
        status: "pending",
        technicianUid: null,
        technicianName: null,
        technicianEmail: null,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp()
      }
    );

    // ถ้าเปิดเคสจากแชท -> แปะเลขเคสกลับไปที่ห้องแชทของลูกค้ารายนั้น (แอดมินเห็นบริบทในแชท)
    if (pendingVisitorRoom) {
      await setDoc(doc(db, "chats", pendingVisitorRoom), {
        caseId: caseRef.id,
        caseNo: caseNo,
      }, { merge: true }).catch(() => {});
      pendingVisitorRoom = null;
    }

    // แจ้งเตือนเฉพาะลูกค้าที่มีบัญชี (วอล์กอินไม่มี UID ให้แจ้งไม่ได้)
    if (customerId) {
      await notifyCustomer(customerId, caseRef.id, caseNo, device, sn, snAutoGenerated);
    }

    Swal.fire({
      icon: "success",
      title: "เปิดเคสเรียบร้อย รอช่างรับงาน",
      timer: 1500,
      showConfirmButton: false,
    });

    // ปิด Modal
    const modal = bootstrap.Modal.getInstance(document.getElementById("createRepair"));
    if (modal) modal.hide();

    // reset
    document.getElementById("customerSelect").value = "";
    document.getElementById("guestName").value = "";
    document.getElementById("guestPhone").value = "";
    document.getElementById("sn").value = "";
    document.getElementById("device").value = "";
    document.getElementById("detail").value = "";
    snAutoGenerated = false;
  } catch (error) {
    console.error(error);

    Swal.fire({
      icon: "error",
      title: "สร้างเคสไม่สำเร็จ",
      text: error.message,
    });
  }
};

// ส่ง notification ให้ลูกค้าเห็นทันทีที่หน้าจอของตัวเอง (customer.html ฟัง realtime อยู่)
// เคสที่เครื่องไม่มี SN เดิม -> ระบบสุ่ม SN ใหม่ให้ตอนชั่งรับงาน จะแจ้งเลข SN ที่ออกให้ชัดเจนในข้อความ

async function notifyCustomer(customerUid, caseId, caseNo, device, sn, isAutoSn) {
  try {
    const message = isAutoSn
      ? `รับเครื่องของคุณแล้ว (ไม่พบ SN เดิม) ระบบจึงออกเลข SN ใหม่ให้: ${sn} — เคส ${caseNo} (${device})`
      : `เปิดเคสซ่อมใหม่ให้คุณแล้ว: เคส ${caseNo} · SN ${sn} (${device})`;

    await addDoc(collection(db, "notifications"), {
      recipientUid: customerUid,
      caseId: caseId,
      caseNo: caseNo,
      sn: sn,
      message,
      read: false,
      createdAt: serverTimestamp(),
    });
  } catch (error) {
    console.error("แจ้งเตือนลูกค้าไม่สำเร็จ", error);
  }
}

// โหลดรายการเคส realtime

function loadRepairCases() {
  onSnapshot(
    collection(db, "repair_cases"),

    (snapshot) => {
      let html = "";

      snapshot.forEach((item) => {
        const c = item.data();

        let date = "-";

        if (c.createdAt) {
          date = c.createdAt.toDate().toLocaleString("th-TH");
        }

        const meta = statusMeta(c.status);

        const badgeClass =
          meta.css === "status-completed" ? "bg-success" :
          meta.css === "status-repairing" ? "bg-info text-dark" :
          meta.css === "status-assigned" ? "bg-primary" :
          "bg-warning text-dark";

        const techCell = c.technicianUid
          ? `${c.technicianName || "-"}`
          : `<span class="badge bg-secondary">ยังไม่มอบหมาย</span>`;

        const noteBtn = c.repairNote
          ? `<button class="btn btn-secondary btn-sm" onclick="viewNote('${item.id}')">
              <i class="fa-solid fa-note-sticky"></i> ดูรายละเอียด
            </button>`
          : "";

        html += `

<tr>


<td>

${c.customerName || "-"}

</td>


<td>

${c.customerEmail || "-"}

</td>



<td>

${c.device || "-"}

</td>



<td>

${c.problem || "-"}

</td>



<td>

<span class="badge ${badgeClass}">

${meta.label}

</span>


</td>

<td>

${techCell}

</td>



<td>

${date}

</td>



<td class="d-flex flex-wrap gap-1">

${noteBtn}

<button

class="btn btn-danger btn-sm"

onclick="deleteCase('${item.id}')">


<i class="fa-solid fa-trash"></i>

ลบ


</button>


</td>



</tr>

`;
      });

      document.getElementById("repairTable").innerHTML = html || `<tr><td colspan="8" class="text-center">ยังไม่มีเคสซ่อม</td></tr>`;
    },
  );
}

// ดู Note ที่ช่างบันทึกไว้ (อ่านอย่างเดียว)

window.viewNote = async (id) => {
  const snap = await getDoc(doc(db, "repair_cases", id));

  const c = snap.data();

  const note = c.repairNote || {};
  const photos = c.faultPhotos || [];

  const photosHtml = photos.length
    ? `<label class="form-label"><b>รูปจุดที่เสีย</b></label>
       <div class="d-flex flex-wrap gap-2 mb-2">
         ${photos.map(url => `
           <a href="${url}" target="_blank" rel="noopener">
             <img src="${url}" style="width:90px;height:90px;object-fit:cover;border-radius:6px;border:1px solid #ddd;">
           </a>
         `).join("")}
       </div>`
    : `<label class="form-label"><b>รูปจุดที่เสีย</b></label><p>ช่างยังไม่ได้แนบรูป</p>`;

  Swal.fire({
    title: "รายละเอียดการซ่อมจากช่าง",

    html: `
      <div class="text-start">
        <label class="form-label"><b>สาเหตุที่เสีย</b></label>
        <p>${note.cause || "-"}</p>
        <label class="form-label"><b>ขั้นตอนการตรวจสอบ / อาการที่พบ</b></label>
        <p>${note.inspection || "-"}</p>
        <label class="form-label"><b>วิธีแก้ไข</b></label>
        <p>${note.repair || "-"}</p>
        <label class="form-label"><b>อะไหล่/อุปกรณ์ที่ใช้</b></label>
        <p>${note.part || "-"}</p>
        <label class="form-label"><b>หมายเหตุจากช่าง</b></label>
        <p>${note.note || "-"}</p>
        ${photosHtml}
      </div>
    `,

    confirmButtonText: "ปิด",
    width: "min(620px, 94vw)",
  });
};

